/// 가입할 때 동의하는 약관 (PRD 8.6.1)
///
/// 이용약관은 PRD 에 본문이 없어 PRD 범위로 쓴 초안입니다. 팀에서 확정 문구를 받으면 이 파일만 바꿉니다.
/// 개인정보 처리방침은 PRD 8.6.1 "개인정보 처리방침에 포함할 내용" 표를 따릅니다.
enum AuthTerms { service, privacy }

/// 약관 화면에 보여줄 제목과 본문
extension AuthTermsX on AuthTerms {
  String get title => switch (this) {
    AuthTerms.service => '이용약관',
    AuthTerms.privacy => '개인정보 처리방침',
  };

  String get body => switch (this) {
    AuthTerms.service => _serviceBody,
    AuthTerms.privacy => _privacyBody,
  };
}

const _serviceBody = '''
제1조 (목적)
이 약관은 모아모아(이하 "서비스")가 제공하는 모임 운영 기능을 이용하는 조건과 절차를 정합니다.

제2조 (서비스 내용)
서비스는 모임 만들기와 가입, 일정 투표와 확정, 공지와 읽음 확인, 출석 기록, 회비·정산 기록 기능을 제공합니다.
회비·정산의 실제 송금은 서비스 밖에서 이루어지며, 서비스는 송금 여부를 직접 확인하지 않습니다.

제3조 (회원가입과 계정)
회원은 이름, 이메일, 비밀번호로 가입하며, 이용약관과 개인정보 처리방침에 모두 동의해야 합니다.
회원은 자신의 계정 정보를 직접 관리해야 하며, 다른 사람의 정보로 가입해서는 안 됩니다.

제4조 (회원의 의무)
회원은 다른 회원의 권리를 침해하거나 법령에 어긋나는 내용을 올려서는 안 됩니다.

제5조 (탈퇴)
회원은 언제든 탈퇴할 수 있습니다. 다만 혼자 관리자로 있는 모임이 있거나, 납부 완료를 제출하지 않은 정산이 있으면 먼저 정리해야 합니다.
탈퇴한 이메일은 탈퇴일로부터 7일 동안 다시 가입할 수 없습니다.

제6조 (약관의 변경)
약관이 바뀌면 서비스 안에서 알립니다.''';

const _privacyBody = '''
1. 수집하는 항목
필수: 이름, 이메일, 비밀번호
선택: 휴대폰 번호

2. 수집 목적
회원 식별, 로그인, 모임 운영 기능 제공, 비밀번호 재설정 안내

3. 보유 기간
회원 탈퇴 시까지 보유합니다.
탈퇴하면 개인정보를 지우고, 정산 기록은 개인을 알 수 없는 상태로 남깁니다.
같은 이메일의 재가입을 7일 동안 막기 위해 이메일 해시만 7일간 보관한 뒤 삭제합니다.

4. 제3자 제공
수집한 개인정보를 제3자에게 제공하지 않습니다.

5. 비밀번호 보호
비밀번호는 원래 값으로 되돌릴 수 없는 방식으로 저장합니다.''';
